// Writes src/harns-settings/scene-previews.js: one frame of each chat backdrop scene, for the pictures on harns
// Settings' Background cards. It runs the scenes from the built agent-chat (run `python scripts/package.py` first), a few
// seconds in on a fixed random seed so the frame is the same each time, and keeps each cell's colour as a tint with
// alpha rather than mixed over a background, so the picture sits on whatever theme Settings shows.
//
//     node scripts/scene-previews.mjs     (npm run previews)
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const BACKDROP = join(REPO, "layouts/harns/mods/agent-chat/backdrop");
const { SCENES } = await import(pathToFileURL(join(BACKDROP, "scenes/index.js")));
const { Palette } = await import(pathToFileURL(join(BACKDROP, "palette.js")));
const { frameRuns } = await import(pathToFileURL(join(BACKDROP, "runs.js")));

// The page each scene plays on, in px, with the chat's 13 px cells: about the shape of a card's picture, big enough
// for a shark or a jellyfish to fit whole.
const WIDTH = 468, HEIGHT = 272, CELL = 13, SECONDS = 5, FPS = 30;
// Brighter than the chat's dim, since the picture is small.
const DIM = 0.7;

/** The theme's palette, but each colour is the tint itself with the opacity as alpha (#rrggbbaa). */
class TintPalette extends Palette {
  mix(r, g, b, a = 1) {
    const byte = v => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, "0");
    // Alpha in 32 steps, so near colours are the same string and merge into one run.
    return `#${byte(r)}${byte(g)}${byte(b)}${byte(Math.round(Math.max(0, Math.min(1, a)) * 31) * 255 / 31)}`;
  }
}

// Each scene's random seed: picked by eye for a frame that shows it well (the sharks crossing in the middle).
const SEEDS = { sharks: 111 };

let seed = 7;
Math.random = () => { seed = (seed * 16807) % 2147483647; return (seed - 1) / 2147483646; };

const previews = {};
for (const s of SCENES) {
  seed = SEEDS[s.id] ?? 7;
  const scene = s.make();
  scene.resize(WIDTH, HEIGHT, CELL * 0.6, Math.round(CELL * 1.3));
  scene.setDim(DIM);
  const pal = new TintPalette({ background: "#000000", foreground: "#dededb", accent: "#e9aa35", done: "#10a7a7" });
  for (let i = 0; i < SECONDS * FPS; i++) scene.frame(1 / FPS, pal);
  const { cols, rows } = scene.grid;
  previews[s.id] = { cols, rows, runs: frameRuns(scene.grid).map(row => row.map(u => [u.col, u.text, u.fg ?? null, u.bg ?? null])) };
}

const out = join(REPO, "src/harns-settings/scene-previews.js");
const body = [
  "// Generated by scripts/scene-previews.mjs (npm run previews): one frame of each chat backdrop scene, for the pictures",
  "// on the Background cards. Each row is a list of runs: [column, text, colour, background], colours as #rrggbbaa tints.",
  `export const SCENE_PREVIEWS = ${JSON.stringify(previews)};`,
  "",
].join("\r\n");
writeFileSync(out, body);
console.log(`Wrote ${out}: ${Object.keys(previews).join(", ")} (${Math.round(body.length / 1024)} KB)`);
